"""Configure local stdio clients for a source checkout or a Windows bundle."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile
import tomllib


NAME = "consumer-cad"
BEGIN = "# BEGIN generated by consumer-cad-ai"
END = "# END generated by consumer-cad-ai"


def write_text(path: Path, contents: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == contents:
        return
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                     dir=path.parent, delete=False) as stream:
        tmp = Path(stream.name)
        try:
            stream.write(contents)
            stream.flush()
        except BaseException:
            stream.close()
            tmp.unlink(missing_ok=True)
            raise
    try:
        tmp.replace(path)
    finally:
        tmp.unlink(missing_ok=True)


def codex_config(existing: str, server: dict) -> str:
    """Preserve unrelated settings. Replace only our delimited generated block."""
    if BEGIN in existing or END in existing:
        if existing.count(BEGIN) != 1 or existing.count(END) != 1:
            raise ValueError("Incomplete consumer-cad block in .codex/config.toml")
        before, sep, after = existing.partition(BEGIN)
        generated, sep, tail = after.partition(END)
        if not sep:
            raise ValueError("Unbalanced consumer-cad block in .codex/config.toml")
        existing = before + tail.lstrip("\r\n")
    if NAME in tomllib.loads(existing).get("mcp_servers", {}):
        raise ValueError("An existing user-managed mcp_servers.consumer-cad already exists")
    env_lines = [f"{key} = {json.dumps(value, ensure_ascii=False)}"
                 for key, value in server["env"].items()]
    generated = "\n".join([
        BEGIN, f"[mcp_servers.{NAME}]",
        f'command = {json.dumps(server["command"], ensure_ascii=False)}',
        f'args = {json.dumps(server["args"], ensure_ascii=False)}',
        "startup_timeout_sec = 90", "tool_timeout_sec = 600",
        f"[mcp_servers.{NAME}.env]", *env_lines, END,
    ])
    result = (existing.rstrip("\n") + "\n\n" if existing.strip() else "") + generated + "\n"
    tomllib.loads(result)
    return result


def configure(root: Path, global_codex: bool = False) -> Path:
    root = root.resolve()
    env = {"CAD_WORKSPACE": str(root / "workspace")}
    portable_python = root / "runtime" / "python" / "python.exe"
    if portable_python.is_file():
        command = portable_python
        args = ["-m", "consumer_cad_ai", "serve"]
        freecad = root / "runtime" / "freecad" / "bin" / "freecadcmd.exe"
        env["FREECAD_CMD"] = str(freecad.resolve(strict=True))
    else:
        bin_dir = root / ".venv" / ("Scripts" if os.name == "nt" else "bin")
        command = bin_dir / ("consumer-cad-mcp.exe" if os.name == "nt" else "consumer-cad-mcp")
        if not command.is_file():
            raise FileNotFoundError(f"Install the project in {root / '.venv'} first")
        args = []
        if os.environ.get("FREECAD_CMD"):
            env["FREECAD_CMD"] = str(Path(os.environ["FREECAD_CMD"]).resolve(strict=True))
    server = {"command": str(command), "args": args, "env": env}
    config = root / ".codex" / "config.toml"
    original = config.read_text(encoding="utf-8") if config.exists() else ""
    contents = codex_config(original, server)
    skill = (root / "skills" / NAME / "SKILL.md").read_text(encoding="utf-8")
    write_text(config, contents)
    write_text(root / ".agents" / "skills" / NAME / "SKILL.md", skill)
    other_clients = root / ".local" / "mcp.json"
    write_text(other_clients, json.dumps({"mcpServers": {NAME: server}}, indent=2,
                                         ensure_ascii=False) + "\n")
    if global_codex:
        from start_codex import codex_command
        cli = codex_command()
        with tempfile.TemporaryDirectory() as neutral:
            listing = subprocess.run([*cli, "mcp", "list", "--json"], cwd=neutral,
                                     check=True, capture_output=True, encoding="utf-8")
            for row in json.loads(listing.stdout):
                if row["name"] == NAME:
                    transport = row["transport"]
                    if (transport.get("command") == str(command) and transport.get("env") == env
                            and transport.get("args", []) == server["args"]):
                        return other_clients
                    raise ValueError("Global consumer-cad registration already exists. Use scripts/cad-codex instead.")
        args = [*cli, "mcp", "add", NAME]
        for key, value in env.items():
            args.extend(["--env", f"{key}={value}"])
        subprocess.run([*args, "--", str(command), *server["args"]], check=True)
    return other_clients


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--global-codex", action="store_true",
                        help="also register this checkout in the user's Codex CLI config")
    args = parser.parse_args()
    print("Configured project MCP and skill. Additional stdio client configuration:",
          configure(Path(__file__).resolve().parents[1], args.global_codex))
